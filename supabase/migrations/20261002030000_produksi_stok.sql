-- Produksi komponen setengah jadi SENGAJA untuk stok, TERPISAH TOTAL dari WO/Raw Schedule:
-- tidak ada FK/join ke panels, raw_schedule, renhar, fcs_timer_kerja. Satu-satunya hubungan ke
-- sisi WO: MEMBACA aturan proses di bom_proses_relevan (aturan yang sama dgn Raw Schedule/Generate
-- Jadwal) saat batch dibuat, lewat komponen BOM acuan tiap item stok.
--
-- Aturan (disetujui user 2 Okt 2026):
--  - Tahap batch = proses relevan komponen BOM acuan yang termasuk POTONG/BENDING/STEL/FINISHING/
--    RENDAM/PAINTING (RAKIT/PASANG/WIRING/QC tidak), urutan produksi. DISALIN saat batch dibuat
--    (perubahan Master Data di tengah jalan gak merusak batch yang berjalan).
--  - qty_selesai = total diproses (TERMASUK reject); baik = selesai - reject. Tidak ada rework.
--  - Tersedia tahap pertama = target - unit hidup (baik tahap pertama - semua reject tahap
--    sesudahnya) -> reject di tahap mana pun diganti potongan BARU. Tahap lain = baik tahap
--    sebelumnya - selesai tahap ini. Tahap bisa jalan paralel.
--  - Selesai = baik tahap terakhir >= target DAN tidak ada WIP -> 1x transaksi 'masuk'
--    (otomatis_produksi) sejumlah baik tahap terakhir. Kurangi target: WIP tetap dituntaskan.
--  - Batal: status batal, baik tahap terakhir yang sudah ada (kalau > 0) tetap masuk stok, WIP
--    ditinggal.
--  - Increment qty ATOMIK di DB, baris batch dikunci (FOR UPDATE) per simpan - operator paralel
--    di tahap yang sama gak saling timpa. Semua validasi di server.
--  - Idempoten berlapis: status aktif->selesai/batal cuma sekali (baris dikunci), penanda
--    stok_transaksi_id, + UNIQUE index referensi transaksi otomatis_produksi.
-- Satu transaksi: gagal di langkah mana pun = batal semua.
-- ============================================================================================
