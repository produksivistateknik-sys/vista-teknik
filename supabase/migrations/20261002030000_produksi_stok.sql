CREATE POLICY produksi_stok_batch_anon_all ON public.produksi_stok_batch FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY produksi_stok_tahap_anon_all ON public.produksi_stok_tahap FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY produksi_stok_log_anon_all   ON public.produksi_stok_log   FOR ALL USING (true) WITH CHECK (true);

-- 3. Tahap berlaku dari aturan WO (bom_proses_relevan) ------------------------------------------
CREATE OR REPLACE FUNCTION public.produksi_stok_tahap_berlaku(p_tipe_panel text, p_kode_komponen text)
RETURNS TABLE (tahap text, urutan smallint) LANGUAGE sql STABLE AS $$
  SELECT r.jenis_pekerjaan, (row_number() OVER (ORDER BY array_position(
           ARRAY['POTONG','BENDING','STEL','FINISHING','RENDAM','PAINTING'], r.jenis_pekerjaan)))::smallint
  FROM (SELECT DISTINCT jenis_pekerjaan FROM public.bom_proses_relevan
        WHERE tipe_panel = p_tipe_panel AND kode_komponen = p_kode_komponen
          AND jenis_pekerjaan IN ('POTONG','BENDING','STEL','FINISHING','RENDAM','PAINTING')) r
  ORDER BY 2;
$$;

-- 4. Kondisi per tahap (SATU rumus, dipakai RPC & dibaca app lewat view) -----------------------
CREATE OR REPLACE FUNCTION public.produksi_stok_kondisi(p_batch_id bigint)
RETURNS TABLE (batch_id bigint, tahap text, urutan smallint, qty_selesai integer, qty_reject integer, qty_baik integer, tersedia integer)
LANGUAGE plpgsql STABLE AS $$
DECLARE b public.produksi_stok_batch; r record; v_prev_baik integer := NULL; v_reject_sesudah integer; v_hidup integer;
BEGIN
  SELECT * INTO b FROM public.produksi_stok_batch WHERE id = p_batch_id;
  IF NOT FOUND THEN RETURN; END IF;
  FOR r IN SELECT t.* FROM public.produksi_stok_tahap t WHERE t.batch_id = p_batch_id ORDER BY t.urutan LOOP
    batch_id := p_batch_id; tahap := r.tahap; urutan := r.urutan;
    qty_selesai := r.qty_selesai; qty_reject := r.qty_reject; qty_baik := r.qty_selesai - r.qty_reject;
    IF v_prev_baik IS NULL THEN
      SELECT COALESCE(SUM(t2.qty_reject),0) INTO v_reject_sesudah FROM public.produksi_stok_tahap t2
        WHERE t2.batch_id = p_batch_id AND t2.urutan > r.urutan;
      v_hidup := qty_baik - v_reject_sesudah;
      tersedia := CASE WHEN b.status = 'aktif' THEN GREATEST(0, b.target_qty - v_hidup) ELSE 0 END;
    ELSE
      tersedia := CASE WHEN b.status = 'aktif' THEN GREATEST(0, v_prev_baik - r.qty_selesai) ELSE 0 END;
    END IF;
    v_prev_baik := qty_baik;
    RETURN NEXT;
  END LOOP;
END $$;

CREATE OR REPLACE VIEW public.v_produksi_stok_tahap WITH (security_invoker = true) AS
  SELECT k.* FROM public.produksi_stok_batch b CROSS JOIN LATERAL public.produksi_stok_kondisi(b.id) k;

-- 5. Cek selesai (internal, dipanggil RPC SETELAH baris batch dikunci) --------------------------
CREATE OR REPLACE FUNCTION public.produksi_stok_cek_selesai(p_batch_id bigint, p_oleh text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE b public.produksi_stok_batch; v_baik_akhir integer; v_wip integer; v_trx public.komponen_stok_transaksi;
BEGIN
  SELECT * INTO b FROM public.produksi_stok_batch WHERE id = p_batch_id;
  IF b.status <> 'aktif' THEN RETURN; END IF;
  SELECT k.qty_baik INTO v_baik_akhir FROM public.produksi_stok_kondisi(p_batch_id) k ORDER BY k.urutan DESC LIMIT 1;
  SELECT COALESCE(SUM(k.tersedia),0) INTO v_wip FROM public.produksi_stok_kondisi(p_batch_id) k WHERE k.urutan > 1;
  IF v_baik_akhir < b.target_qty OR v_wip > 0 THEN RETURN; END IF;
  SELECT * INTO v_trx FROM public.catat_transaksi_stok(b.komponen_id, 'masuk', v_baik_akhir, 'otomatis_produksi',
    'Produksi stok batch #' || b.id || ' selesai', 'produksi_stok_batch:' || b.id, COALESCE(p_oleh, 'SISTEM'), current_date, NULL);
  UPDATE public.produksi_stok_batch SET status = 'selesai', selesai_at = now(), updated_at = now(), stok_transaksi_id = v_trx.id
  WHERE id = p_batch_id;
END $$;

-- Ringkasan batch utk dikembalikan RPC
CREATE OR REPLACE FUNCTION public.produksi_stok_ringkasan(p_batch_id bigint)
RETURNS json LANGUAGE sql STABLE AS $$
  SELECT json_build_object(
    'batch', (SELECT row_to_json(b) FROM public.produksi_stok_batch b WHERE b.id = p_batch_id),
    'tahap', (SELECT json_agg(row_to_json(k) ORDER BY k.urutan) FROM public.produksi_stok_kondisi(p_batch_id) k));
$$;

-- 6. RPC ----------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.buat_batch_produksi_stok(p_komponen_id bigint, p_target_qty integer, p_created_by text)
RETURNS json LANGUAGE plpgsql AS $$
DECLARE k public.komponen_stok; v_id bigint; v_n integer;
BEGIN
  IF p_target_qty IS NULL OR p_target_qty <= 0 THEN RAISE EXCEPTION 'Target qty harus lebih dari 0'; END IF;
  SELECT * INTO k FROM public.komponen_stok WHERE id = p_komponen_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Komponen stok % tidak ditemukan', p_komponen_id; END IF;
  IF k.bom_tipe_panel IS NULL OR k.bom_kode_komponen IS NULL THEN
    RAISE EXCEPTION 'Komponen "%" belum punya komponen BOM acuan - isi dulu di Stok Komponen', k.nama;
  END IF;
  SELECT COUNT(*) INTO v_n FROM public.produksi_stok_tahap_berlaku(k.bom_tipe_panel, k.bom_kode_komponen);
  IF v_n = 0 THEN
    RAISE EXCEPTION 'Komponen BOM acuan % % tidak punya proses POTONG s/d PAINTING di Master Data proses relevan', k.bom_tipe_panel, k.bom_kode_komponen;
  END IF;
  INSERT INTO public.produksi_stok_batch (komponen_id, target_qty, bom_tipe_panel, bom_kode_komponen, created_by)
  VALUES (p_komponen_id, p_target_qty, k.bom_tipe_panel, k.bom_kode_komponen, p_created_by) RETURNING id INTO v_id;
  INSERT INTO public.produksi_stok_tahap (batch_id, tahap, urutan)
  SELECT v_id, t.tahap, t.urutan FROM public.produksi_stok_tahap_berlaku(k.bom_tipe_panel, k.bom_kode_komponen) t;
  RETURN public.produksi_stok_ringkasan(v_id);
END $$;

CREATE OR REPLACE FUNCTION public.simpan_progress_produksi_stok(
  p_batch_id bigint, p_tahap text, p_qty integer, p_qty_reject integer, p_foto_urls text[],
  p_operator_id bigint, p_operator_nama text, p_catatan text DEFAULT NULL, p_mulai_at timestamptz DEFAULT NULL
) RETURNS json LANGUAGE plpgsql AS $$
DECLARE b public.produksi_stok_batch; v_tersedia integer; v_reject integer := COALESCE(p_qty_reject, 0);
BEGIN
  SELECT * INTO b FROM public.produksi_stok_batch WHERE id = p_batch_id FOR UPDATE;  -- serialisasi per batch
  IF NOT FOUND THEN RAISE EXCEPTION 'Batch produksi % tidak ditemukan', p_batch_id; END IF;
  IF b.status <> 'aktif' THEN RAISE EXCEPTION 'Batch produksi sudah %, tidak bisa ditambah progress', b.status; END IF;
  IF p_qty IS NULL OR p_qty <= 0 THEN RAISE EXCEPTION 'Jumlah selesai sesi ini harus lebih dari 0'; END IF;
  IF v_reject < 0 OR v_reject > p_qty THEN RAISE EXCEPTION 'Jumlah reject harus antara 0 dan %', p_qty; END IF;
  IF p_foto_urls IS NULL OR cardinality(p_foto_urls) < 1 THEN RAISE EXCEPTION 'Foto hasil wajib diisi minimal 1'; END IF;
  SELECT k.tersedia INTO v_tersedia FROM public.produksi_stok_kondisi(p_batch_id) k WHERE k.tahap = p_tahap;
  IF NOT FOUND THEN RAISE EXCEPTION 'Tahap % tidak berlaku untuk batch ini', p_tahap; END IF;
  IF p_qty > v_tersedia THEN
    RAISE EXCEPTION 'Jumlah melebihi yang tersedia di tahap % (maksimal % pcs saat ini)', p_tahap, v_tersedia;
  END IF;
  UPDATE public.produksi_stok_tahap
    SET qty_selesai = qty_selesai + p_qty, qty_reject = qty_reject + v_reject, updated_at = now()
  WHERE batch_id = p_batch_id AND tahap = p_tahap;
  INSERT INTO public.produksi_stok_log (batch_id, tahap, qty_sesi_ini, qty_reject_sesi_ini, foto_urls, operator_id, operator_nama, catatan, mulai_at)
  VALUES (p_batch_id, p_tahap, p_qty, v_reject, p_foto_urls, p_operator_id, p_operator_nama, p_catatan, p_mulai_at);
  UPDATE public.produksi_stok_batch SET updated_at = now() WHERE id = p_batch_id;
  PERFORM public.produksi_stok_cek_selesai(p_batch_id, p_operator_nama);
  RETURN public.produksi_stok_ringkasan(p_batch_id);
END $$;

CREATE OR REPLACE FUNCTION public.ubah_target_produksi_stok(p_batch_id bigint, p_target_qty integer, p_oleh text)
RETURNS json LANGUAGE plpgsql AS $$
DECLARE b public.produksi_stok_batch;
BEGIN
  SELECT * INTO b FROM public.produksi_stok_batch WHERE id = p_batch_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Batch produksi % tidak ditemukan', p_batch_id; END IF;
  IF b.status <> 'aktif' THEN RAISE EXCEPTION 'Batch produksi sudah %, target tidak bisa diubah', b.status; END IF;
  IF p_target_qty IS NULL OR p_target_qty <= 0 THEN RAISE EXCEPTION 'Target qty harus lebih dari 0'; END IF;
  UPDATE public.produksi_stok_batch SET target_qty = p_target_qty, updated_at = now() WHERE id = p_batch_id;
  PERFORM public.produksi_stok_cek_selesai(p_batch_id, p_oleh);
  RETURN public.produksi_stok_ringkasan(p_batch_id);
END $$;

CREATE OR REPLACE FUNCTION public.batal_produksi_stok(p_batch_id bigint, p_oleh text, p_alasan text DEFAULT NULL)
RETURNS json LANGUAGE plpgsql AS $$
DECLARE b public.produksi_stok_batch; v_baik_akhir integer; v_trx public.komponen_stok_transaksi;
BEGIN
  SELECT * INTO b FROM public.produksi_stok_batch WHERE id = p_batch_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Batch produksi % tidak ditemukan', p_batch_id; END IF;
  IF b.status <> 'aktif' THEN RAISE EXCEPTION 'Batch produksi sudah %, tidak bisa dibatalkan', b.status; END IF;
  SELECT k.qty_baik INTO v_baik_akhir FROM public.produksi_stok_kondisi(p_batch_id) k ORDER BY k.urutan DESC LIMIT 1;
  IF COALESCE(v_baik_akhir, 0) > 0 THEN
    SELECT * INTO v_trx FROM public.catat_transaksi_stok(b.komponen_id, 'masuk', v_baik_akhir, 'otomatis_produksi',
      'Produksi stok batch #' || b.id || ' DIBATALKAN - barang jadi yang sudah ada dimasukkan', 'produksi_stok_batch:' || b.id,
      COALESCE(p_oleh, 'SISTEM'), current_date, NULL);
  END IF;
  UPDATE public.produksi_stok_batch
    SET status = 'batal', updated_at = now(), selesai_at = now(), dibatalkan_oleh = p_oleh, alasan_batal = p_alasan,
        stok_transaksi_id = v_trx.id
  WHERE id = p_batch_id;
  RETURN public.produksi_stok_ringkasan(p_batch_id);
END $$;

