-- 1. Komponen BOM acuan per item stok --------------------------------------------------------
ALTER TABLE public.komponen_stok
  ADD COLUMN IF NOT EXISTS bom_tipe_panel    text,
  ADD COLUMN IF NOT EXISTS bom_kode_komponen text;
COMMENT ON COLUMN public.komponen_stok.bom_kode_komponen IS 'Komponen BOM acuan (bom_master.kode_komponen, bersama bom_tipe_panel). Tahap Produksi Stok dibaca dari bom_proses_relevan acuan ini - satu aturan dgn WO.';
-- Backfill (keputusan user: acuan tipe FS): UNP->FS.10 UNP, HGR->FS.19 Hanger, FR-*->FS.1 Frame.
UPDATE public.komponen_stok SET bom_tipe_panel = 'FS',
  bom_kode_komponen = CASE WHEN jenis = 'UNP' THEN 'FS.10' WHEN jenis = 'HGR' THEN 'FS.19' WHEN jenis LIKE 'FR-%' THEN 'FS.1' END
WHERE bom_kode_komponen IS NULL AND (jenis IN ('UNP','HGR') OR jenis LIKE 'FR-%');

-- 2. Tabel -----------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.produksi_stok_batch (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  komponen_id        bigint  NOT NULL REFERENCES public.komponen_stok(id) ON DELETE RESTRICT,
  target_qty         integer NOT NULL CHECK (target_qty > 0),
  status             text    NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif','selesai','batal')),
  bom_tipe_panel     text    NOT NULL,   -- snapshot acuan saat batch dibuat
  bom_kode_komponen  text    NOT NULL,
  stok_transaksi_id  bigint  REFERENCES public.komponen_stok_transaksi(id) ON DELETE SET NULL,
  created_by         text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  selesai_at         timestamptz,
  dibatalkan_oleh    text,
  alasan_batal       text
);
CREATE INDEX IF NOT EXISTS produksi_stok_batch_status_idx ON public.produksi_stok_batch (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.produksi_stok_tahap (
  batch_id     bigint   NOT NULL REFERENCES public.produksi_stok_batch(id) ON DELETE CASCADE,
  tahap        text     NOT NULL CHECK (tahap IN ('POTONG','BENDING','STEL','FINISHING','RENDAM','PAINTING')),
  urutan       smallint NOT NULL,
  qty_selesai  integer  NOT NULL DEFAULT 0 CHECK (qty_selesai >= 0),
  qty_reject   integer  NOT NULL DEFAULT 0 CHECK (qty_reject >= 0 AND qty_reject <= qty_selesai),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (batch_id, tahap),
  UNIQUE (batch_id, urutan)
);

CREATE TABLE IF NOT EXISTS public.produksi_stok_log (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id             bigint  NOT NULL REFERENCES public.produksi_stok_batch(id) ON DELETE CASCADE,
  tahap                text    NOT NULL,
  qty_sesi_ini         integer NOT NULL CHECK (qty_sesi_ini > 0),
  qty_reject_sesi_ini  integer NOT NULL DEFAULT 0 CHECK (qty_reject_sesi_ini >= 0 AND qty_reject_sesi_ini <= qty_sesi_ini),
  foto_urls            text[]  NOT NULL CHECK (cardinality(foto_urls) >= 1),
  operator_id          bigint,
  operator_nama        text,
  catatan              text,
  mulai_at             timestamptz,
  created_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS produksi_stok_log_batch_idx ON public.produksi_stok_log (batch_id, created_at DESC);

-- Idempotensi lapis DB: 1 batch = maks 1 transaksi stok otomatis.
CREATE UNIQUE INDEX IF NOT EXISTS komponen_stok_transaksi_produksi_unik
  ON public.komponen_stok_transaksi (referensi) WHERE sumber = 'otomatis_produksi';

-- RLS: pola tabel app lain (otentikasi di level app).
ALTER TABLE public.produksi_stok_batch ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.produksi_stok_tahap ENABLE ROW LEVEL SECURITY;
